    public static List<Recipe> filter(String query, int maxCalories, int maxMinutes, String type) {
        String q = query == null ? "" : query.trim();
        String t = type == null ? "All" : type;
        List<Recipe> out = new ArrayList<>();
        for (Recipe recipe : all()) {
            boolean matchesQuery = recipe.matchesSearchQuery(q);
            boolean matchesCalories = maxCalories <= 0 || recipe.getCalories() <= maxCalories;
            boolean matchesMinutes = maxMinutes <= 0 || recipe.getMinutes() <= maxMinutes;
            boolean matchesType = "All".equalsIgnoreCase(t) || recipe.getType().equalsIgnoreCase(t);
            if (matchesQuery && matchesCalories && matchesMinutes && matchesType) {
                out.add(recipe);
            }
        }
        return out;
    }

    public static List<Recipe> byMealType(String mealType) {
        String type;
        if ("Lunch".equalsIgnoreCase(mealType)) {
            type = "Lunch";
        } else if ("Dinner".equalsIgnoreCase(mealType)) {
            type = "Dinner";
        } else if ("Snack".equalsIgnoreCase(mealType)) {
            type = "Snack";
        } else {
            type = "Breakfast";
        }
        return filter("", 0, 0, type);
    }

    public static Recipe byId(String id) {
        for (Recipe recipe : all()) {
            if (recipe.getId().equals(id)) {
                return recipe;
            }
        }
        return null;
    }

    /** Localized label for Breakfast / Lunch / Dinner (matches meal spinner). */
    public static String localizedMealType(Context context, String typeEn) {
        if (typeEn == null) {
            return "";
        }
        String[] values = context.getResources().getStringArray(R.array.meal_type_values);
        String[] labels = context.getResources().getStringArray(R.array.meal_type_labels);
        for (int i = 0; i < values.length; i++) {
            if (values[i].equalsIgnoreCase(typeEn)) {
                return labels[i];
            }
        }
        return typeEn;
    }
